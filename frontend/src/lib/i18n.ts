const LANG_LABELS: Record<Lang, string> = { fr: "FR", en: "EN", de: "DE", es: "ES" };
const LANG_FLAGS: Record<Lang, string> = { fr: "🇫🇷", en: "🇬🇧", de: "🇩🇪", es: "🇪🇸" };

export function useTranslation() {
  const [lang, setLangState] = useState<Lang>("fr");

  useEffect(() => {
    const saved = (typeof window !== "undefined" ? localStorage.getItem("vista_lang") : null) as Lang | null;
    if (saved && translations[saved]) setLangState(saved);
  }, []);

  function setLang(l: Lang) {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("vista_lang", l);
  }

  function t(key: string): string {
    return translations[lang]?.[key] || translations["en"]?.[key] || key;
  }

  return { lang, setLang, t, langs: Object.keys(translations) as Lang[], LANG_LABELS, LANG_FLAGS };
}
